#!/usr/bin/env python3
"""Generate engine constants plus the pinned CoopDX behavior-ID adapter."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADERS = (
    "include/sm64.h",
    "include/model_ids.h",
    "include/mario_animation_ids.h",
    "include/object_constants.h",
    "include/surface_terrains.h",
    "include/audio_defines.h",
    "src/game/level_update.h",
    "src/game/object_list_processor.h",
    "src/game/save_file.h",
    "src/game/interaction.h",
)
PREFIXES = (
    "ACT_", "INPUT_", "PARTICLE_", "MODEL_", "MARIO_ANIM_", "INTERACT_",
    "OBJ_FLAG_", "SURFACE_", "SOUND_", "SEQ_", "WARP_", "OBJ_LIST_",
    "SAVE_FLAG_", "MARIO_",
)
DEFINITION = re.compile(r"^\s*#define\s+([A-Z][A-Z0-9_]+)\s+")
BEHAVIOR = re.compile(r"^\s*extern\s+const\s+BehaviorScript\s+([A-Za-z_][A-Za-z0-9_]*)\[\];")
COOPDX_BEHAVIOR_ID = re.compile(r"^id_[A-Za-z0-9_]+$")
COMMENTED_SOUND = re.compile(
    r"^\s*/\*\s*not verified\s*\*/\s*#define\s+(SOUND_[A-Z0-9_]+)\s+(.+?)\s*$"
)

names = set()
commented_sounds = {}
for header in HEADERS:
    for line in (ROOT / header).read_text(errors="ignore").splitlines():
        sound = COMMENTED_SOUND.match(line)
        if sound:
            expression = sound.group(2).split("//", 1)[0].strip()
            commented_sounds[sound.group(1)] = expression
            continue
        match = DEFINITION.match(line)
        if match and match.group(1).startswith(PREFIXES):
            names.add(match.group(1))

behaviors = sorted(set(
    match.group(1)
    for line in (ROOT / "include/behavior_data.h").read_text(errors="ignore").splitlines()
    if (match := BEHAVIOR.match(line))
))
upstream_behavior_ids = [
    line.strip()
    for line in (ROOT / "tools/coopdx_behavior_ids.txt").read_text().splitlines()
    if line.strip() and not line.lstrip().startswith("#")
]
if not upstream_behavior_ids or any(not COOPDX_BEHAVIOR_ID.fullmatch(value) for value in upstream_behavior_ids):
    raise SystemExit("tools/coopdx_behavior_ids.txt is empty or malformed")
if len(upstream_behavior_ids) != len(set(upstream_behavior_ids)):
    raise SystemExit("tools/coopdx_behavior_ids.txt contains duplicate behavior IDs")
native_behavior_names = {name for name in behaviors}

output = ROOT / "src/pc/mods/mod_constants.inc"
with output.open("w") as stream:
    stream.write("/* Generated by tools/generate_mod_constants.py from engine headers. */\n")
    for name in sorted(names):
        stream.write(f"#ifdef {name}\n    expose_int(\"{name}\", {name});\n#endif\n")
    # The audio bank header deliberately comments out several IDs whose bank
    # address is unverified. CoopDX scripts still use these symbolic IDs; the
    # encoded value is available to native playback through SOUND_ARG_LOAD.
    for name, expression in sorted(commented_sounds.items()):
        stream.write(f'    expose_int("{name}", {expression});\n')

with (ROOT / "src/pc/mods/mod_behavior_weak.inc").open("w") as stream:
    stream.write("/* Generated by tools/generate_mod_constants.py from behavior_data.h. */\n")
    stream.write("/* Missing symbols are possible in host-only adapter tests. */\n")
    for behavior in behaviors:
        stream.write(f"#pragma weak {behavior}\n")

with (ROOT / "src/pc/mods/mod_behavior_constants.inc").open("w") as stream:
    stream.write("/* Generated by tools/generate_mod_constants.py from the pinned CoopDX ID list. */\n")
    for behavior_id, lua_name in enumerate(upstream_behavior_ids):
        stream.write(f'    expose_int("{lua_name}", {behavior_id});\n')
    stream.write(f'    expose_int("id_bhv_max_count", {len(upstream_behavior_ids)});\n')

with (ROOT / "src/pc/mods/mod_behavior_entries.inc").open("w") as stream:
    stream.write("/* Generated from the pinned CoopDX ID list and local behavior_data.h. */\n")
    stream.write("/* A null script means the upstream behavior is absent from this engine. */\n")
    for behavior_id, lua_name in enumerate(upstream_behavior_ids):
        behavior = lua_name[3:]
        script = behavior if behavior in native_behavior_names else "NULL"
        stream.write(f'    {{ {behavior_id}, "{lua_name}", {script} }},\n')
