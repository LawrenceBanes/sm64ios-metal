#!/usr/bin/env python3
"""Generate the vanilla numeric constant surface available to Lua mods."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADERS = (
    "include/sm64.h",
    "include/model_ids.h",
    "include/mario_animation_ids.h",
    "include/object_constants.h",
    "include/surface_terrains.h",
    "include/audio_defines.h",
    "src/game/level_update.h",
    "src/game/object_list_processor.h",
    "src/game/save_file.h",
    "src/game/interaction.h",
)
PREFIXES = (
    "ACT_", "INPUT_", "PARTICLE_", "MODEL_", "MARIO_ANIM_", "INTERACT_",
    "OBJ_FLAG_", "SURFACE_", "SOUND_", "SEQ_", "WARP_", "OBJ_LIST_",
    "SAVE_FLAG_", "MARIO_",
)
DEFINITION = re.compile(r"^\s*#define\s+([A-Z][A-Z0-9_]+)\s+")
COMMENTED_SOUND = re.compile(
    r"^\s*/\*\s*not verified\s*\*/\s*#define\s+(SOUND_[A-Z0-9_]+)\s+(.+?)\s*$"
)

names = set()
commented_sounds = {}
for header in HEADERS:
    for line in (ROOT / header).read_text(errors="ignore").splitlines():
        sound = COMMENTED_SOUND.match(line)
        if sound:
            expression = sound.group(2).split("//", 1)[0].strip()
            commented_sounds[sound.group(1)] = expression
            continue
        match = DEFINITION.match(line)
        if match and match.group(1).startswith(PREFIXES):
            names.add(match.group(1))

output = ROOT / "src/pc/mods/mod_constants.inc"
with output.open("w") as stream:
    stream.write("/* Generated by tools/generate_mod_constants.py from engine headers. */\n")
    for name in sorted(names):
        stream.write(f"#ifdef {name}\n    expose_int(\"{name}\", {name});\n#endif\n")
    # The audio bank header deliberately comments out several IDs whose bank
    # address is unverified. CoopDX scripts still use these symbolic IDs; the
    # encoded value is available to native playback through SOUND_ARG_LOAD.
    for name, expression in sorted(commented_sounds.items()):
        stream.write(f'    expose_int("{name}", {expression});\n')
